/** One `[x, y, width]` per horizontal run of ink, so an icon is a handful of rectangles. */
export function runs(grid: readonly string[]): [number, number, number][] {
  return grid.flatMap((row, y) => [...row.matchAll(/#+/g)].map((m) => [m.index ?? 0, y, m[0].length] as [number, number, number]));
}
